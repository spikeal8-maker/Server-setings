"""Owner-invoked maintenance preparation; no application restart or data rewrite."""
import datetime as dt
import contextlib
import sqlite3
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import uuid

from .store import OpsError, process_identity, now


def require(value, code):
    if not value:
        raise OpsError(code, code)


class ReadonlyStore:
    def __init__(self,root):self.path=Path(root)/'operations.sqlite3'
    @contextlib.contextmanager
    def db(self):
        db=sqlite3.connect(self.path.as_uri()+'?mode=ro',uri=True)
        db.row_factory=sqlite3.Row
        try:yield db
        finally:db.close()


def instance(root):
    path=Path(root)/'.asa/installation.json'
    value=json.loads(path.read_text(encoding='utf-8')) if path.exists() else {}
    return value.get('instanceId')


def check_generation(root, plan):
    require(plan.get('installation_instance_id')==instance(root),'STALE_INSTALLATION')


def private_directory(path, uid, *, apply=False):
    path=Path(path)
    require(path.is_absolute() and path.resolve()==path,'BACKUP_PATH_SYMLINK')
    if path.exists():
        require(path.is_dir() and path.stat().st_uid==uid,'BACKUP_OWNER')
        require(path.stat().st_mode & 0o077 == 0,'BACKUP_PERMISSIONS')
    elif apply:
        # Only one directory is created; the explicitly selected parent must exist.
        require(path.parent.is_dir(),'BACKUP_PARENT_MISSING')
        path.mkdir(mode=0o700)
        if os.getuid()==0:os.chown(path,uid,-1)
    return path


def supersede(store, installation, opid, proof, *, apply=False):
    """Proof is generated by attest_replacement(), never accepted from MCP callers."""
    with store.db() as db:
        db.execute('BEGIN IMMEDIATE' if apply else 'BEGIN')
        row=db.execute('SELECT * FROM operations WHERE id=? AND installation=?',(opid,installation)).fetchone()
        require(row is not None,'OPERATION_NOT_FOUND')
        prior=json.loads(row['result']) if row['result'] else {}
        if row['status']=='superseded':
            require(prior.get('replacement',{}).get('proof_sha256')==proof['proof_sha256'],'REPLACEMENT_PROOF_CHANGED')
            return {'operation_id':opid,'status':'superseded','reused':True}
        require(row['status']=='recovery_required','NOT_INTERRUPTED_OPERATION')
        require(not db.execute("SELECT 1 FROM operations WHERE installation=? AND status IN ('queued','running')",(installation,)).fetchone(),'ACTIVE_OPERATION')
        identity=process_identity(row['pid']) if row['pid'] else None
        require(not identity or identity!=row['process_identity'],'LIVE_WORKER')
        require(dt.datetime.fromisoformat(row['created']) < dt.datetime.fromisoformat(proof['new_volumes_after']),'OPERATION_NOT_FROM_OLD_INSTALLATION')
        if apply:
            db.execute("UPDATE operations SET status='superseded',phase='installation_replaced',updated=?,result=? WHERE id=?",
                (now(),json.dumps({**prior,'replacement':proof,'previous_status':row['status']}),opid))
    return {'operation_id':opid,'status':'superseded' if apply else 'would_supersede','reused':False}


def attest_replacement(install, receipt):
    """Attest the explicit completed clean-reinstall evidence against the live engine."""
    receipt=Path(receipt)
    technical=receipt.with_name('final-technical-receipt.json')
    for path in (receipt,technical):
        require(path.resolve()==path and path.stat().st_uid==0 and path.stat().st_mode & 0o022==0,'REPLACEMENT_RECEIPT_TRUST')
    clean=json.loads(receipt.read_text());audit=json.loads(technical.read_text())
    require(clean['phase']=='technical_verified' and clean.get('current_data_preserved') is False,'NOT_COMPLETED_CLEAN_REINSTALL')
    current=install.readiness();records=install.identity()
    require(clean['revision']==audit['revision']==current['revision'] and int(audit['schema'])==int(current['schema']),'REPLACEMENT_RUNTIME_DRIFT')
    old=set(clean['old_container_ids']);require(len(old)==7,'OLD_CONTAINER_EVIDENCE')
    all_ids=set(install.compose('ps','-a','-q','--no-trunc',capture=True).split())
    # Inspect all containers as well, so renaming/relabeling an old one cannot hide it.
    from deployment.system import run
    live_ids=set(run(['docker','ps','-aq','--no-trunc'],capture=True).split())
    require(not old & live_ids and len(all_ids)==7,'OLD_CONTAINERS_REMAIN')
    volumes={m['Name'] for service in ('postgres','minio') for m in records[service]['mounts'] if m.get('Type')=='volume'}
    actual=json.loads(run(['docker','volume','inspect',*sorted(volumes)],capture=True))
    created={v['Name']:v['CreatedAt'] for v in actual}
    require(created==audit['new_volume_created_at'] and len(created)==2,'REPLACEMENT_VOLUME_DRIFT')
    require(all((v.get('Labels') or {}).get('com.docker.compose.project')==install.project for v in actual),'REPLACEMENT_VOLUME_OWNER')
    return {'proof_sha256':hashlib.sha256(receipt.read_bytes()+technical.read_bytes()).hexdigest(),
        'revision':current['revision'],'schema':int(current['schema']),
        'new_volumes_after':min(created.values()),'reason':'explicitly verified complete project replacement'}


def prepare(config, *, apply=False, replacement_receipt=None, operation_id=None):
    import sys
    root=Path(config['root'])
    require(root.is_absolute() and root.resolve()==root,'INSTALLATION_ROOT')
    require(root.stat().st_uid==config['owner_uid'],'INSTALLATION_OWNER')
    sys.path.insert(0,str(root/'tools'))
    from deployment.system import Installation, operation_lock
    from deployment.contracts import atomic_json, DEFAULT_WINDOW
    install=Installation(root,config['profile'])
    require(install.project==config['project'],'INSTALLATION_PROJECT')
    with operation_lock(root) if apply else contextlib.nullcontext():
        install.identity();current=install.readiness()
        from .store import Store
        store=Store(config['state_root']) if apply else ReadonlyStore(config['state_root'])
        if apply:
            require(subprocess.run(['systemctl','is-active','--quiet','asa-operations.service']).returncode!=0,'STOP_OPERATIONS_SERVICE_FIRST')
            with store.db() as db:
                require(not db.execute("SELECT 1 FROM operations WHERE installation=? AND status IN ('queued','running')",(config['id'],)).fetchone(),'ACTIVE_OPERATION')
        settings=dict(install.settings)
        target=private_directory(settings.get('backupDirectory') or config.get('backup_directory') or root/'backups',config['owner_uid'],apply=apply)
        ident=settings.get('instanceId') or uuid.uuid4().hex
        require(bool(re.fullmatch('[a-f0-9]{32}',ident)),'INSTANCE_ID')
        require(bool(replacement_receipt)==bool(operation_id),'REPLACEMENT_ARGUMENTS')
        proof=None;retired=None
        if replacement_receipt:
            from .store import Store, identifier
            proof=attest_replacement(install,replacement_receipt)
            proof['instance_id']=ident
            # Validate retirement before persisting settings; repeat transaction on apply.
            supersede(store,config['id'],identifier(operation_id),proof)
        if apply:
            require(os.access(target,os.W_OK),'BACKUP_NOT_WRITABLE')
            atomic_json(install.state/'installation.json',{**settings,'format':'asa-installation-v1',
                'profile':install.profile,'project':install.project,'automaticUpdates':settings.get('automaticUpdates',False),
                'window':settings.get('window',DEFAULT_WINDOW),'backupDirectory':str(target),'instanceId':ident})
            if os.getuid()==0:os.chown(install.state/'installation.json',config['owner_uid'],-1)
        if proof:retired=supersede(store,config['id'],operation_id,proof,apply=apply)
        return {'mode':'apply' if apply else 'plan','revision':current['revision'],'schema':current['schema'],
            'backup_directory':str(target),'instance_id':ident if apply or settings.get('instanceId') else 'generate_on_apply',
            'old_operation':retired,'application_restarted':False,'data_changed':False}
